/**
 * Читает недавние смайлики из localStorage.
 *
 * Returns:
 *   Список emoji-строк.
 */
export function getRecentEmojis() {
  try {
    const raw = localStorage.getItem(RECENT_KEY);
    if (!raw) {
      return [...DEFAULT_RECENT];
    }
    const parsed = JSON.parse(raw);
    if (!Array.isArray(parsed)) {
      return [...DEFAULT_RECENT];
    }
    const cleaned = parsed
      .filter((item) => typeof item === 'string' && item)
      .slice(0, RECENT_LIMIT);
    return cleaned.length ? cleaned : [...DEFAULT_RECENT];
  } catch {
    return [...DEFAULT_RECENT];
  }
}

/**
 * Добавляет emoji в начало списка недавних.
 *
 * Args:
 *   emoji: вставленный символ.
 *
 * Returns:
 *   Обновлённый список недавних.
 */
export function pushRecentEmoji(emoji) {
  const value = String(emoji || '');
  if (!value) {
    return getRecentEmojis();
  }
  const next = [
    value,
    ...getRecentEmojis().filter((item) => item !== value),
  ].slice(0, RECENT_LIMIT);
  try {
    localStorage.setItem(RECENT_KEY, JSON.stringify(next));
  } catch {
    // ignore quota / private mode
  }
  return next;
}

/**
 * Категории панели, включая «Недавние».
 *
 * Returns:
 *   Массив категорий для UI.
 */
export function getEmojiPanelCategories() {
  return [
    {
      id: 'recent',
      title: 'Недавние',
      icon: '🕒',
      items: getRecentEmojis(),
    },
    ...EMOJI_CATEGORIES,
  ];
}
